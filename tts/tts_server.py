#!/usr/bin/env python3
"""GPU text-to-speech service for the race commentator (Chatterbox on the DGX Spark).

English uses Chatterbox-Turbo (fastest); Dutch and French use Chatterbox-Multilingual.
One GPU worker thread renders requests in priority order, so commentary, debrief verdicts
and anything else can be submitted concurrently without fighting over the GPU.

  POST /tts     {"text": "...", "lang": "en|nl|fr", "kind": "commentary|debrief"}  -> audio/wav
                headers X-Text-Tokens / X-Speech-Tokens / X-Audio-Ms report the exact tokens used
  GET  /health  -> {"ready": bool, "busy": bool, "queue": n, "last_ms": ..., "count": ...}

Usage: tts/.venv/bin/python tts/tts_server.py [port]   (default: $TTS_PORT or 8766)
"""
import io
import itertools
import json
import os
import queue
import sys
import threading
import time
import warnings
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

warnings.filterwarnings("ignore")
os.environ.setdefault("TQDM_DISABLE", "1")

PORT = int(sys.argv[1]) if len(sys.argv) > 1 else int(os.environ.get("TTS_PORT", "8766"))
MAX_QUEUE = 3                      # stale commentary is dropped beyond this
STATE = {"ready": False, "error": None, "busy": False, "count": 0, "last_ms": 0, "dropped": 0, "models": []}
JOBS = queue.PriorityQueue()
SEQ = itertools.count()
MODELS = {}
LAST = {"text": 0, "speech": 0}    # exact token counts of the clip being rendered (single GPU worker)


def count_tokens(t3, method):
    """Wrap the T3 text->speech-token model to record exactly how many tokens go in and come out."""
    orig = getattr(t3, method)

    def wrapped(*a, **kw):
        tt = kw.get("text_tokens")
        out = orig(*a, **kw)
        LAST["text"] = int(tt.shape[-1]) if tt is not None else 0     # one sequence (CFG duplicates are not new input)
        LAST["speech"] = int(out.shape[-1])                            # speech tokens generated by the model
        return out
    setattr(t3, method, wrapped)


def load_models():
    try:
        import torch
        from chatterbox.mtl_tts import ChatterboxMultilingualTTS
        from chatterbox.tts_turbo import ChatterboxTurboTTS
        t = time.time()
        MODELS["turbo"] = ChatterboxTurboTTS.from_pretrained(device="cuda")
        MODELS["mtl"] = ChatterboxMultilingualTTS.from_pretrained(device="cuda")
        count_tokens(MODELS["turbo"].t3, "inference_turbo")
        count_tokens(MODELS["mtl"].t3, "inference")
        STATE["models"] = ["Chatterbox-Turbo (EN)", "Chatterbox-Multilingual (NL/FR)"]
        # warm up both paths so the first real line is fast
        with torch.inference_mode():
            MODELS["turbo"].generate("Ready to race.")
            MODELS["mtl"].generate("Klaar om te racen.", language_id="nl")
        STATE["ready"] = True
        print(f"TTS ready in {time.time() - t:.1f}s", flush=True)
    except Exception as e:  # keep serving /health so the game can fall back to text only
        STATE["error"] = repr(e)
        print("TTS failed to load:", e, flush=True)


def synth(text, lang):
    import soundfile as sf
    import torch
    with torch.inference_mode():
        if lang == "en":
            m = MODELS["turbo"]
            wav = m.generate(text)
        else:
            m = MODELS["mtl"]
            wav = m.generate(text, language_id=lang, exaggeration=0.7, cfg_weight=0.3)
    buf = io.BytesIO()
    samples = wav.squeeze().float().cpu().numpy()
    sf.write(buf, samples, m.sr, format="WAV", subtype="PCM_16")
    return buf.getvalue(), {"text": LAST["text"], "speech": LAST["speech"], "audio_ms": int(len(samples) * 1000 / m.sr)}


def worker():
    while True:
        _, _, job = JOBS.get()
        if job["kind"] == "commentary" and time.time() - job["t"] > 6:
            STATE["dropped"] += 1             # too old to be relevant on track any more
            job["result"] = None
            job["done"].set()
            continue
        STATE["busy"] = True
        t = time.time()
        try:
            LAST.update(text=0, speech=0)
            job["result"], job["tokens"] = synth(job["text"], job["lang"])
            STATE["count"] += 1
            STATE["last_ms"] = int((time.time() - t) * 1000)
        except Exception as e:
            print("synth error:", e, flush=True)
            job["result"] = None
        STATE["busy"] = False
        job["done"].set()


class Handler(BaseHTTPRequestHandler):
    def _json(self, obj, code=200):
        body = json.dumps(obj).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        if self.path == "/health":
            return self._json(dict(STATE, queue=JOBS.qsize()))
        self._json({"error": "not found"}, 404)

    def do_POST(self):
        if self.path != "/tts":
            return self._json({"error": "not found"}, 404)
        if not STATE["ready"]:
            return self._json({"error": "loading"}, 503)
        try:
            n = int(self.headers.get("Content-Length", 0) or 0)
            if n < 0 or n > 10000:
                return self._json({"error": "request too large"}, 413)
            req = json.loads(self.rfile.read(n) or b"{}")
            text = str(req.get("text", "")).strip()[:400]
            lang = req.get("lang", "en") if req.get("lang") in ("en", "nl", "fr") else "en"
            kind = "debrief" if req.get("kind") == "debrief" else "commentary"
        except ValueError:
            return self._json({"error": "bad request"}, 400)
        if not text:
            return self._json({"error": "empty"}, 400)
        if kind == "commentary" and JOBS.qsize() >= MAX_QUEUE:
            STATE["dropped"] += 1
            return self._json({"error": "busy"}, 429)
        job = {"text": text, "lang": lang, "kind": kind, "t": time.time(), "done": threading.Event(), "result": None}
        JOBS.put((0 if kind == "commentary" else 1, next(SEQ), job))   # live commentary first
        if not job["done"].wait(30) or job["result"] is None:
            return self._json({"error": "dropped"}, 504)
        self.send_response(200)
        self.send_header("Content-Type", "audio/wav")
        self.send_header("Content-Length", str(len(job["result"])))
        self.send_header("X-TTS-Ms", str(STATE["last_ms"]))
        self.send_header("X-Text-Tokens", str(job["tokens"]["text"]))
        self.send_header("X-Speech-Tokens", str(job["tokens"]["speech"]))
        self.send_header("X-Audio-Ms", str(job["tokens"]["audio_ms"]))
        self.end_headers()
        self.wfile.write(job["result"])

    def log_message(self, fmt, *args):
        pass


if __name__ == "__main__":
    threading.Thread(target=load_models, daemon=True).start()
    threading.Thread(target=worker, daemon=True).start()
    print(f"TTS service on http://127.0.0.1:{PORT}", flush=True)
    ThreadingHTTPServer(("127.0.0.1", PORT), Handler).serve_forever()
